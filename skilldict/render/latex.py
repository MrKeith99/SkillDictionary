"""The release as the rulebook's own LaTeX.

tex() writes a challenge's {scorelist} for the rulebook's scoresheet macros
(external/RuleBook/setup/macros_scoresheets.tex), so it drops into
documents/scoresheets.tex in place of the hand-written file. It keeps the
rulebook's sections and ends with the score per skill.

pdf() typesets one PDF with, per challenge, the rulebook's official sheet next
to the release's generated one. It compiles in build/latex/, a copy of the
pinned RuleBook, with the preamble of the rulebook's own
documents/scoresheets.tex, so nothing in the submodule is touched and no
rulebook source is copied into this repo. Needs latexmk and a TeX distribution.

The interactive referee sheets are tabs of dist/scoring.html (render/page.py).
"""
import os, shutil, subprocess
from collections import OrderedDict
from .. import paths


def out_path(b, slug, ext):
    return os.path.join(paths.BUILD, "sheets", f"{slug}.{ext}")


def skill_max(b, slug):
    out = OrderedDict()
    for it in b.challenges[slug]["entries"]:
        e = b.variants[it["ref"]]
        p = e.get("points") or 0
        if p > 0:
            out[e["skill"]] = out.get(e["skill"], 0) + p * it.get("count", 1)
    return out


# ── rulebook LaTeX ───────────────────────────────────────────────────────────
def tex_esc(s):
    s = str(s)
    for a, c in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\^{}")):
        s = s.replace(a, c)
    return s


def tex(b, slug):
    """The challenge's lines, written with the rulebook's macros. Each
    description carries its id; {scorelist} adds the Special Penalties &
    Bonuses itself."""
    D, ch = b.variants, b.challenges[slug]
    # Lines keep the challenge file's order, which follows the rulebook. A line
    # with related_variant in the same section as its parent is a modifier of
    # that parent (\scoremod / \scorepen); everything else is an item.
    entries = [it for it in ch["entries"] if D[it["ref"]]["type"] != "administrative"]
    section_of = {it["ref"]: it.get("section") for it in entries}

    def note(e):
        # Only the id, flush right on the item's own line if it fits, else on
        # the next line without stretching the description (TeXbook p.106).
        return (r"\unskip\nobreak\hfil\penalty50\hskip0.4em\hbox{}\nobreak\hfill"
                r"\mbox{\tiny\color[gray]{0.4}\texttt{" + tex_esc(e["id"]) + r"}}\hspace{0.6em}")

    def line(it):
        e = D[it["ref"]]
        n, pts = it.get("count", 1), e.get("points") or 0
        mult = f"[{n}]" if n > 1 else ""
        desc = tex_esc(e["description"]) + note(e)
        parent = it.get("related_variant")
        if e.get("points") is None:              # judged on the day, e.g. a percentage
            return f"\t\\scoreitem{{0}}{{{desc}}}"
        if parent and section_of.get(parent) == it.get("section"):
            macro = r"\scorepen" if pts < 0 else r"\scoremod"
            return f"\t\t{macro}{mult}{{{pts}}}{{{desc}}}"
        if e["type"] == "penalty":
            return f"\t\\penaltyitem{mult}{{{abs(pts)}}}{{{desc}}}"
        return f"\t\\scoreitem{mult}{{{pts}}}{{{desc}}}"

    # the start-signal penalty only where the challenge lists it
    opts = [f"timelimit={ch.get('max_time_minutes', 5)}"]
    if "SPECIAL-02" not in {it["ref"] for it in ch["entries"]}:
        opts.insert(0, "startbutton=false")
    out = ["% GENERATED by `skilldict sheets` from the skill dictionary.",
           "% Do not edit; change data/ and regenerate.",
           # \small, as the rulebook already does for Restaurant: the ids and
           # the skill table must fit on the sheet's page.
           f"\\small\\begin{{scorelist}}[{','.join(opts)}]", ""]
    sec = object()
    for it in entries:
        if it.get("section") != sec:
            sec = it.get("section")
            out += ["", f"\t\\scoreheading{{{tex_esc(sec)}}}"] if sec else [""]
        out.append(line(it))
    out.append("")
    if ch.get("max_score"):                  # not every line is reachable in one run
        out.append(f"\t\\setTotalScore{{{ch['max_score']}}}")
    out += [r"\end{scorelist}", "",
            r"\vspace{0.2em}\noindent\begin{minipage}{\textwidth}\small",   # heading + table stay together
            r"\textbf{Score by skill} {\footnotesize (comparable across challenges; penalties count against their skill)}\\",
            r"\begin{tabularx}{\textwidth}{@{}X r c @{\hspace{2em}} X r c@{}}",
            r"\textbf{Skill} & \textbf{Max} & \textbf{Scored} & \textbf{Skill} & \textbf{Max} & \textbf{Scored}\\\hline"]
    cells = [f"\\texttt{{{tex_esc(n)}}} & \\textit{{{m}}} & \\scoreline[0.1]"
             for n, m in sorted(skill_max(b, slug).items(), key=lambda x: -x[1])]
    if len(cells) % 2:
        cells.append("& &")
    half = len(cells) // 2                       # read down the left column first
    out += [f"{x} & {y}\\\\" for x, y in zip(cells[:half], cells[half:])]
    out += [r"\end{tabularx}", r"\end{minipage}", ""]
    path = out_path(b, slug, "tex")
    paths.write_text("\n".join(out), path)
    return path


def pdf(b):
    work = os.path.join(paths.BUILD, "latex")
    shutil.copytree(paths.RULEBOOK, work, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns(".git", ".build"))
    official = b.release.sheets
    ref_version = b.rulebook_version
    label = "generated from the skill dictionary" if b.release.in_force else f"{b.release.year} PROPOSAL (draft)"
    body = []
    for slug in sorted(b.challenges):
        name = b.challenges[slug]["challenge"]
        src = tex(b, slug)
        mine = f"skilldict_{slug}"
        shutil.copy(src, os.path.join(work, "scoresheets", f"{mine}.tex"))
        pages = []
        if official.get(slug):
            pages.append((f"{name} --- official sheet (Rulebook {ref_version})", name, official[slug]))
        pages.append((f"{name} --- {label}", f"{name} ({label})", mine))
        for foot, test, sheet in pages:
            body += [rf"\renewcommand{{\footline}}{{{tex_esc(foot)}}}",
                     rf"\renewcommand{{\currentTest}}{{{tex_esc(test)}}}",
                     r"\begin{scoresheet}", rf"\input{{scoresheets/{sheet}}}", r"\end{scoresheet}"]
    doc = "skilldict"
    with open(os.path.join(work, "documents", "scoresheets.tex")) as fh:
        preamble = fh.read().split(r"\begin{document}")[0]
    paths.write_text(preamble + "\n".join([r"\begin{document}", r"\pagestyle{plain}",
                                           r"\renewcommand{\shortScoresheet}{false}", *body,
                                           r"\end{document}", ""]),
                     os.path.join(work, "documents", f"{doc}.tex"))
    log = os.path.join(work, f"{doc}.log")
    with open(log, "w") as fh:
        r = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-outdir=.build",
                            f"documents/{doc}.tex"], cwd=work, stdout=fh, stderr=subprocess.STDOUT)
    pdf = os.path.join(work, ".build", f"{doc}.pdf")
    if r.returncode or not os.path.exists(pdf):
        raise RuntimeError(f"latexmk failed, see {paths.rel(log)}")
    out = os.path.join(paths.BUILD, f"sheets_{b.release.year}_vs_rulebook_{ref_version}.pdf")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    shutil.copy(pdf, out)
    return out
